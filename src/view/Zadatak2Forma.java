    private void jButtonIzmeniActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonIzmeniActionPerformed
       int selektovaniProfa = jTable1.getSelectedRow();
        if (selektovaniProfa == -1) {
            JOptionPane.showMessageDialog(this, "Morate da izaberete koga cete da izmenite", "Greska", JOptionPane.ERROR_MESSAGE);
            return;
            }
        Status status = Status.AKTIVAN;
        Profesor profa = kontroler.ucitajProfesoreIzBaze().get(selektovaniProfa);
        if (!profa.getStatus().equals(status)) {
         JOptionPane.showMessageDialog(this, "Mozete menjati samo aktivne profesore", "Greska", JOptionPane.ERROR_MESSAGE);
         return;
        }
        
        IzmeniForma izf = new IzmeniForma(this, true,profa);
        izf.setVisible(true);
         
        osveziTabelu();
        
    }//GEN-LAST:event_jButtonIzmeniActionPerformed

