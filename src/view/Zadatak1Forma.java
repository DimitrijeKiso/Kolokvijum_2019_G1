    private void popuniCBProizvodi() {
        jComboBoxProizvodi.removeAllItems();
        List<Proizvod> listaProizvoda = new ArrayList();
        listaProizvoda = kontroler.getListaProizvoda();
        for (Proizvod proizvod : listaProizvoda) {
            jComboBoxProizvodi.addItem(proizvod);
        }
        
    }

    private void popuniCBProizvodjaci() {
        jComboBoxProizvodjac.removeAllItems();
        List<Proizvodjac> listaProizvodjaca = new ArrayList();
        listaProizvodjaca = kontroler.getListaProizvodjaca();
        for (Proizvodjac proizvodjac : listaProizvodjaca) {
            jComboBoxProizvodjac.addItem(proizvodjac); 
        }
    }

    private void popuniCBPoreskeStope() {
        jComboBoxPoreskaStopa.removeAllItems();
        List<PoreskaStopa> listaPoreskihStopa = new ArrayList();
        listaPoreskihStopa = kontroler.getListaPoreskihStopa();
        for (PoreskaStopa poreskaStopa : listaPoreskihStopa) {
            jComboBoxPoreskaStopa.addItem(poreskaStopa); 
        }
    }
